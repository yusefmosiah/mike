#!/usr/bin/env python3
"""Generate the Standard layers section of infra/workstation/README.md.

The layer manifest (infra/workstation/layers.json) is the source of truth: the
guest reads it at /etc/layers.json, the backend mirrors it for turn context,
and this script writes the operator-facing list. Run it after editing the
manifest; CI-oriented tests cover the manifest/mirror contract separately.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "infra" / "workstation" / "layers.json"
README = ROOT / "infra" / "workstation" / "README.md"
START = "<!-- generated:capability-list -->"
END = "<!-- /generated -->"


def table_cell(value: object) -> str:
    """Keep a manifest string inside one Markdown table cell."""
    return (
        str(value)
        .replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("\n", " ")
        .strip()
    )


def main() -> int:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    layers = manifest.get("layers")
    if not isinstance(layers, dict) or not layers:
        print(f"{MANIFEST}: expected a non-empty 'layers' object", file=sys.stderr)
        return 1

    lines = [
        START,
        "## Standard layers",
        "",
        "Every workstation gets the same list. `layer use <name> -- <command>` "
        "checks a layer out of the Nix store on first use, records the checkout "
        "in the host ledger, and puts it on PATH for that command; `layer list` "
        "prints the same entries. The manifest is `layers.json`; the backend "
        "mirrors it in `backend/src/lib/workstation/layers.ts`, and a test fails "
        "when they drift. This section is generated by "
        "`scripts/docs/generate-capability-list.py`; edit the manifest, then "
        "re-run the script.",
        "",
        "| Layer | Purpose | Enter | Unlocks |",
        "| --- | --- | --- | --- |",
    ]
    details: list[str] = []
    for name, layer in layers.items():
        purpose = table_cell(layer.get("purpose", ""))
        unlocks = table_cell(layer.get("unlocks", ""))
        lines.append(
            f"| `{name}` | {purpose} | `layer use {name}` | `{unlocks}` |"
        )
        note = layer.get("note")
        env = layer.get("env") or {}
        env_text = ", ".join(f"`{key}={value}`" for key, value in env.items())
        parts = []
        if note:
            parts.append(str(note).strip())
        if env_text:
            parts.append(f"Exports {env_text} when entered.")
        if parts:
            sentences = " ".join(
                part if part.endswith((".", "!", "?")) else f"{part}."
                for part in parts
            )
            details.append(f"- **{name}:** {sentences}")

    if details:
        lines.extend(["", *details])
    lines.append(END)

    text = README.read_text(encoding="utf-8")
    updated, replacements = re.subn(
        re.escape(START) + r".*?" + re.escape(END),
        "\n".join(lines),
        text,
        count=1,
        flags=re.DOTALL,
    )
    if replacements != 1:
        print(
            f"{README}: expected one {START} ... {END} block",
            file=sys.stderr,
        )
        return 1

    README.write_text(updated, encoding="utf-8")
    print(f"updated {README.relative_to(ROOT)} ({len(layers)} layers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
